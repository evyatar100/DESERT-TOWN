"""TG57 Batch 2: write Plugins/zDesertScreens/002a_area_names.rb (map id -> approved Hebrew area label).

Labels come from share-page/areas.he.json (founder-approved, dec:tg-25). A map with no label of
its own takes its nearest labelled parent; a map with none at all is left out, so the stock name shows.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GF = ROOT / "game-files"
OUT = GF / "Plugins" / "zDesertScreens" / "002a_area_names.rb"
sys.path.insert(0, str(GF))

from tests.event_catalog import _attr  # noqa: E402
from tests.rx_loader import load_rxdata  # noqa: E402


def _text(v):
    return v.decode("utf-8", "replace") if isinstance(v, bytes) else str(getattr(v, "text", v))


def area_key(folder):
    return "deep-playa" if folder.startswith("deep-playa-") else folder


def build():
    names = {k: v["name"] for k, v in json.loads((ROOT / "share-page/areas.he.json").read_text(encoding="utf-8"))["areas"].items()}
    status = json.loads((ROOT / "maps/status.json").read_text(encoding="utf-8"))["maps"]
    by_id = {r["map_id"]: area_key(r["id"]) for r in status if r.get("map_id") and not r.get("deprecated")}
    infos = load_rxdata(GF / "Data" / "MapInfos.rxdata")
    lower = {k.lower(): k for k in names}
    parent = {int(k): int(_attr(v, "@parent_id") or 0) for k, v in infos.items()}
    own = {}
    for mid, v in infos.items():
        key = by_id.get(int(mid)) or lower.get(_text(_attr(v, "@name")).lower())
        if key in names:
            own[int(mid)] = key
    out = {}
    for mid in sorted(parent):
        cur, seen = mid, set()
        while cur and cur not in seen:
            seen.add(cur)
            if cur in own:
                out[mid] = names[own[cur]]
                break
            cur = parent.get(cur, 0)
    return out


def main():
    rows = build()
    lines = ["# Generated by assets-factory/desert_screens/areas.py (TG57); do not edit by hand.",
             "module DesertScreens", "  AREA_NAMES = {"]
    lines += [f'    {mid} => "{name}",' for mid, name in rows.items()]
    lines += ["  }.freeze", "end", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT), len(rows), "maps")


if __name__ == "__main__":
    main()
